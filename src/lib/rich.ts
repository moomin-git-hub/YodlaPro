import DOMPurify from 'dompurify';
import katex from 'katex';

/** Card text can be legacy plain/markdown-ish text or HTML from the rich editor. */
export const isHtml = (s: string) => /<\/?(b|i|u|s|strong|em|p|div|br|h[1-6]|ul|ol|li|sub|sup|span|code|pre|a|img|mark|font)\b/i.test(s);

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Legacy plain text → HTML (keeps **bold**, *italic*, `code`, ``` fences, links, newlines). */
function plainToHtml(s: string) {
  let h = esc(s);
  h = h.replace(/```(\w*)\n?([\s\S]*?)```/g, (_, _l, c) => `<pre><code>${c.replace(/\n$/, '')}</code></pre>`);
  h = h.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>').replace(/(^|[^*\w])\*(?!\s)(.+?)\*(?!\*)/g, '$1<i>$2</i>').replace(/`([^`\n]+)`/g, '<code>$1</code>');
  h = h.replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, '<a href="$2">$1</a>');
  return h.replace(/\n/g, '<br>');
}

/** Cloze: {{c1::answer::hint}} → hidden on the front for the target number, highlighted on the back. */
export const CLOZE = /\{\{c(\d+)::([\s\S]+?)(?:::([\s\S]+?))?\}\}/g;
export const clozeIndices = (s: string) => [...new Set([...s.matchAll(CLOZE)].map((m) => +m[1]))].sort((a, b) => a - b);
export function clozeHtml(s: string, idx: number, revealed: boolean) {
  return s.replace(CLOZE, (_m, n, ans, hint) => (+n !== idx ? ans : revealed ? `<span class="cloze-a">${ans}</span>` : `<span class="cloze-q">[${hint ?? '…'}]</span>`));
}
export const clozePlain = (s: string) => s.replace(CLOZE, (_m, _n, a) => a);

function renderMath(html: string) {
  // $$display$$, $inline$, \( \), \[ \]
  return html
    .replace(/\$\$([\s\S]+?)\$\$|\\\[([\s\S]+?)\\\]/g, (_, a, b) => safeTex(a ?? b, true))
    .replace(/\$([^$\n<]+?)\$|\\\(([\s\S]+?)\\\)/g, (_, a, b) => safeTex(a ?? b, false));
}
function safeTex(tex: string, display: boolean) {
  const t = tex.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
  try { return katex.renderToString(t, { displayMode: display, throwOnError: false, output: 'html' }); } catch { return esc(tex); }
}

let hooked = false;
function hook() {
  if (hooked) return;
  hooked = true;
  DOMPurify.addHook('afterSanitizeAttributes', (n) => {
    if (n.tagName === 'A') { n.setAttribute('target', '_blank'); n.setAttribute('rel', 'noopener noreferrer'); }
  });
}

export function sanitize(html: string) {
  hook();
  return DOMPurify.sanitize(html, {
    ALLOWED_TAGS: ['b', 'strong', 'i', 'em', 'u', 's', 'strike', 'del', 'p', 'div', 'br', 'h1', 'h2', 'h3', 'h4', 'ul', 'ol', 'li', 'sub', 'sup', 'span', 'code', 'pre', 'a', 'img', 'mark', 'font', 'blockquote', 'hr'],
    ALLOWED_ATTR: ['href', 'src', 'alt', 'style', 'color', 'class', 'target', 'rel'],
    ALLOWED_URI_REGEXP: /^(?:https?:|data:image\/(?:png|jpe?g|webp|gif);|blob:|\/)/i,
  });
}

/** Final HTML for display: sanitize → math. KaTeX output is generated by us, so it's added after sanitizing. */
export function toDisplayHtml(s: string) {
  if (!s) return '';
  return renderMath(sanitize(isHtml(s) ? s : plainToHtml(s)));
}

/** One-line plain preview for lists, search and TTS. */
export function plainText(s: string) {
  if (!s) return '';
  if (!isHtml(s)) return clozePlain(s);
  const d = document.createElement('div');
  d.innerHTML = sanitize(s.replace(/<(br|\/p|\/div|\/li|\/h\d)>/gi, ' $&'));
  return clozePlain(d.textContent ?? '').replace(/\s+/g, ' ').trim();
}

export const isBlank = (s: string) => !plainText(s).trim() && !/<img/i.test(s);
